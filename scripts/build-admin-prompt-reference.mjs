// Build-time only: derive the admin's read-only templates from the real provider
// sources. No request bodies, learner data or secrets are captured.
import ts from 'typescript';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { format } from 'prettier';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const definitions = [
  ['translation', 'תרגום ובחירת משמעות מתוך הקשר.', 'enrichment/providers/openai.ts'],
  ['reading', 'יצירת קטע קריאה לפי נושא, רמה ואוצר מילים.', 'reading/openai-reading.ts'],
  [
    'courses',
    'תכנון קורס והוראות לשלבי האבחון, השיעורים ושיעורי הבית.',
    'courses/course.service.ts',
    'courses/course.provider.ts',
    'admin/admin.service.ts',
    'private-lessons/private-lesson.content.ts',
    'private-lessons/private-lesson.planner.ts',
    'private-lessons/private-lesson.activity.ts',
  ],
  [
    'lesson-summary',
    'סיכום וניתוח ראיות אחרי שיעור פרטי.',
    'private-lessons/private-lesson.summary.ts',
  ],
  [
    'lesson-live',
    'התנהגות המורה, שפות, תיקונים וזרימת שיעור בזמן אמת.',
    'private-lessons/private-lesson.prompt.ts',
    'private-lessons/private-lesson.directives.ts',
  ],
  ['image-generation', 'יצירת איור לפי המשמעות שנבחרה.', 'practice/openai-study-image.provider.ts'],
  [
    'image-brief',
    'פירוש משמעות המילה להנחיה חזותית.',
    'practice/openai-study-image-brief.resolver.ts',
  ],
  [
    'word-pack-examples',
    'משפט דוגמה קצר למילה מתוך יחידת לימוד.',
    'word-packs/word-pack-example.provider.ts',
  ],
];
const catalog = {};
for (const [key, description, ...files] of definitions) {
  const templates = [];
  for (const file of files) {
    const source = (await readFile(path.join(root, 'src/modules', file), 'utf8')).replace(/\r\n/g, '\n');
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
    const add = (name, node) => {
      if (
        node &&
        node.getText(ast).length > 40 &&
        !templates.some((t) => t.text === node.getText(ast))
      )
        templates.push({ name, text: ts.isStringLiteral(node) ? node.text : node.getText(ast) });
    };
    const visit = (node) => {
      if (
        ts.isPropertyAssignment(node) &&
        node.name.getText(ast) === 'instructions' &&
        !ts.isIdentifier(node.initializer) &&
        !ts.isCallExpression(node.initializer)
      )
        add(`${file}: instructions`, node.initializer);
      if (
        ts.isVariableDeclaration(node) &&
        [
          'instructions',
          'planInstruction',
          'prompt',
          'privateLessonBriefInstruction',
          'adaptivePlanInstruction',
          'adaptiveScopeInstruction',
          'exitTaskInstruction',
          'bankSchedulingInstruction',
        ].includes(node.name.getText(ast))
      )
        add(`${file}: ${node.name.getText(ast)}`, node.initializer);
      if (ts.isFunctionDeclaration(node) && node.name?.text === 'instructions')
        add(`${file}: translation template`, node.body);
      if (
        ts.isFunctionDeclaration(node) &&
        ['buildPrivateLessonPrompt', 'defaultLessonDirectives'].includes(node.name?.text)
      ) {
        // Include conditional policy fragments as well as the final template.
        const fragment = (part) => {
          if (ts.isTemplateExpression(part) || ts.isNoSubstitutionTemplateLiteral(part))
            add('Live lesson template / conditional policy', part);
          ts.forEachChild(part, fragment);
        };
        fragment(node.body);
        return;
      }
      if (
        ts.isCallExpression(node) &&
        ts.isPropertyAccessExpression(node.expression) &&
        node.expression.name.text === 'generate' &&
        node.arguments.length >= 4
      ) {
        const instruction = node.arguments[3];
        if (ts.isStringLiteral(instruction) || ts.isTemplateExpression(instruction))
          add(`${file}: ${node.arguments[2].getText(ast)}`, instruction);
      }
      ts.forEachChild(node, visit);
    };
    visit(ast);
  }
  if (!templates.length) throw new Error(`No source instructions found for ${key}`);
  catalog[key] = { description, templates };
}
const output = await format(
  `// Generated by scripts/build-admin-prompt-reference.mjs. Do not edit by hand.\nexport const promptReference = ${JSON.stringify(catalog, null, 2)} as const;\n`,
  {
    parser: 'typescript',
    ...JSON.parse(await readFile(path.join(root, '.prettierrc.json'), 'utf8').catch(() => '{}')),
  },
);
const destination = path.join(root, 'src/modules/admin/admin.prompt-reference.generated.ts');
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw new Error('Admin prompt reference is stale; regenerate it');
} else await writeFile(destination, output);
