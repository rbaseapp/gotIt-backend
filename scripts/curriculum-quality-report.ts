// Writes docs/CURRICULUM_QUALITY_REPORT.md for the served english-zero-c1 content.
// Usage: npm run audit:curriculum
import { writeFileSync } from 'node:fs';
import { auditCurriculum, COVERAGE_MIN } from '../src/modules/curriculum/curriculum.quality.js';
// The served content: curriculum.json with introduction-update.json applied.
import { content, lexicon } from '../src/modules/curriculum/curriculum.content.js';

// Frequency-coverage word cards are taught per unit outside the dialogue.
const cards = new Map<string, string[]>();
for (const t of lexicon.targets)
  if (t.track !== 'communicative') cards.set(t.unit, [...(cards.get(t.unit) ?? []), t.en]);
const report = auditCurriculum(content, cards);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

const lines = [
  '# Curriculum quality report — english-zero-c1',
  '',
  'Generated by `npm run audit:curriculum` (src/modules/curriculum/curriculum.quality.ts).',
  'Thresholds are product starting points to calibrate in a pilot, not validated norms.',
  '',
  '## Summary by band',
  '',
  '| Band | Units | Mean targets per unit | Lessons over new-word budget | Median passage coverage | Below 95% coverage | Units with uncontracted speech | Uncontracted lines | Targets absent from dialogue+passage | Reviewed |',
  '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|',
  ...report.summary.map(
    (b) =>
      `| ${b.band} | ${b.units} | ${b.meanTargets.toFixed(1)} | ${b.overBudget} | ${pct(b.medianCoverage)} | ${b.belowCoverageMin} | ${b.unitsWithUncontracted} | ${b.uncontractedLines} | ${b.targetsNotInInput} | ${b.reviewed} |`,
  ),
  '',
  `Phonics words that use a grapheme not yet taught: ${report.phonicsNotDecodable}.`,
  '',
  '## Phonics',
  '',
  ...report.phonics
    .filter((p) => p.notDecodable.length || p.exerciseNotDecodable.length)
    .map((p) => `- ${p.id}: ${[...p.notDecodable, ...p.exerciseNotDecodable].join(', ')}`),
  '',
  '## Units',
  '',
];
for (const u of report.units) {
  const issues: string[] = [];
  if (u.overBudget)
    issues.push(
      `${u.newPerSession} new targets in one lesson (budget ${u.budget[0]}–${u.budget[1]})`,
    );
  if (u.passageCoverage < COVERAGE_MIN)
    issues.push(
      `passage coverage ${pct(u.passageCoverage)}; unknown: ${u.unknownInPassage.slice(0, 12).join(', ')}`,
    );
  if (u.targetsNotInInput.length)
    issues.push(
      `targets absent from the dialogue and passage (drilled only in exercises): ${u.targetsNotInInput.join(', ')}`,
    );
  if (u.uncontracted.length)
    issues.push(
      `uncontracted speech: ${u.uncontracted
        .slice(0, 4)
        .map((x) => `"${x.line}" → ${x.suggestion}`)
        .join('; ')}${u.uncontracted.length > 4 ? ` (+${u.uncontracted.length - 4})` : ''}`,
    );
  if (!issues.length) continue;
  lines.push(`### ${u.id} (${u.band})`, '', ...issues.map((i) => `- ${i}`), '');
}
writeFileSync('docs/CURRICULUM_QUALITY_REPORT.md', lines.join('\n'));
console.table(
  report.summary.map((b) => ({
    ...b,
    medianCoverage: pct(b.medianCoverage),
    meanTargets: b.meanTargets.toFixed(1),
  })),
);
console.log('phonics not decodable:', report.phonicsNotDecodable);
